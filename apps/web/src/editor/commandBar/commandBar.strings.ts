/**
 * The words of the command bar inside the palette and of the «עוזר השפה» Settings section (ADR-0027), Hebrew first and English
 * with the same keys (commandBar.strings.test.ts keeps parity: same keys, no empty string, same {placeholders}). The fixed product
 * wording shared with the server (the refusals, the setup states, the stages, the never-sent list) is in packages/i18n
 * commandBar.ts and is read through `barText`; the words here are the bar's own: headings, footers, the sentence of each step
 * detail, the notes, the actions, the intents and the Settings fields.
 *
 * Placeholders are {name} and are filled by `fill`. A value that must keep its own direction (a time, a dB value, a frame
 * number, a typed name) is wrapped by `ltr()` or `auto()` (Unicode isolates), which BarPreview turns into <bdi> elements.
 * No string says the assistant is connected or that a model answered: wave 1 has no network adapter.
 */
import { dictionaries, type Key, type Lang } from '@pulseframe/i18n';

/** Isolates: LRI/FSI … PDI. `ltr` is for times, numbers and dB; `auto` is for the owner's own words (names, quoted text). */
export const LRI = '⁦';
export const FSI = '⁨';
export const PDI = '⁩';
export const ltr = (s: string | number): string => `${LRI}${s}${PDI}`;
export const auto = (s: string): string => `${FSI}${s}${PDI}`;
/** Removes the isolates (for the live region and aria-labels, where a screen reader gets plain words). */
export const plain = (s: string): string => s.replace(/[⁦⁨⁩]/g, '');

export const fill = (s: string, vars: Record<string, string | number> = {}): string => s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));

