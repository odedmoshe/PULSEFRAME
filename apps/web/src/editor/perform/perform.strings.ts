export type PerformKey = keyof typeof he;
export const PERFORM_STRINGS: Readonly<Record<Lang, Record<PerformKey, S>>> = { he, en };
/** A translator for the view's own strings; `{name}` placeholders are filled from `vars`. */
export const performT = (lang: Lang) => (key: PerformKey, vars?: Record<string, string | number>): S => {
  const s = PERFORM_STRINGS[lang][key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
};
